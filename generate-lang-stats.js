/**
 * Aggregate language bytes across all repos the token can see,
 * render compact SVG cards, and write them to assets/.
 * Usage: GITHUB_TOKEN=... node generate-lang-stats.js
 */
const fs = require("fs");
const path = require("path");

const TOKEN = process.env.GITHUB_TOKEN || process.env.STATS_PAT || process.env.SNAKE_PAT;
if (!TOKEN) {
  console.error("Missing GITHUB_TOKEN / STATS_PAT / SNAKE_PAT");
  process.exit(1);
}

const API = "https://api.github.com";
const headers = {
  Authorization: `Bearer ${TOKEN}`,
  Accept: "application/vnd.github+json",
  "User-Agent": "22ABLE22-profile-stats",
  "X-GitHub-Api-Version": "2022-11-28",
};

async function gh(url) {
  const res = await fetch(url, { headers });
  if (!res.ok) {
    const text = await res.text().catch(() => res.statusText);
    throw new Error(`${res.status} ${url} ${text.slice(0, 200)}`);
  }
  return res.json();
}

const PALETTE = {
  Python: "#3572A5",
  JavaScript: "#f1e05a",
  TypeScript: "#3178c6",
  HTML: "#e34c26",
  CSS: "#563d7c",
  C: "#555555",
  "C++": "#f34b7d",
  Cuda: "#3A4E3A",
  Jupyter: "#DA5B0B",
  "Jupyter Notebook": "#DA5B0B",
  Shell: "#89e051",
  Batchfile: "#C1F12E",
  GDScript: "#355570",
  Markdown: "#083fa1",
  Rust: "#dea584",
  Java: "#b07219",
  Go: "#00ADD8",
  PHP: "#4F5D95",
  Vue: "#41b883",
  SCSS: "#c6538c",
};

function colorFor(name) {
  return PALETTE[name] || "#8b949e";
}

function escapeXml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function renderTopLangs(langs, total) {
  // compact stacked bars + labels
  const entries = langs.slice(0, 8);
  const width = 420;
  const rowH = 28;
  const headerH = 40;
  const height = headerH + entries.length * rowH + 28;
  const barMaxW = width - 36;
  const parts = [];
  parts.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`,
  );
  parts.push(
    `<style>
      .bg{fill:#0d1117}
      .card{fill:#010409;stroke:#30363d}
      .title{fill:#e6edf3;font:600 14px -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif}
      .label{fill:#e6edf3;font:600 12px -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif}
      .pct{fill:#8b949e;font:400 12px -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif}
      .sub{fill:#8b949e;font:400 11px -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif}
    </style>`,
  );
  parts.push(`<rect class="card" x="1" y="1" width="${width - 2}" height="${height - 2}" rx="8"/>`);
  parts.push(`<text class="title" x="18" y="26">Most Used Languages</text>`);
  parts.push(
    `<text class="sub" x="18" y="${height - 14}">Includes private repos · generated by GitHub Actions</text>`,
  );

  let y = headerH + 8;
  // overall stacked bar
  let x = 18;
  for (const [name, bytes] of entries) {
    const w = total > 0 ? (bytes / total) * barMaxW : 0;
    parts.push(
      `<rect x="${x.toFixed(1)}" y="34" width="${Math.max(w, 1).toFixed(1)}" height="8" rx="2" fill="${colorFor(name)}"/>`,
    );
    x += w;
  }

  y = headerH + 22;
  for (const [name, bytes] of entries) {
    const pct = total > 0 ? ((bytes / total) * 100).toFixed(1) : "0.0";
    parts.push(`<circle cx="24" cy="${y}" r="5" fill="${colorFor(name)}"/>`);
    parts.push(`<text class="label" x="36" y="${y + 4}">${escapeXml(name)}</text>`);
    parts.push(
      `<text class="pct" x="${width - 18}" y="${y + 4}" text-anchor="end">${pct}%</text>`,
    );
    y += rowH;
  }
  parts.push(`</svg>`);
  return parts.join("\n");
}

function renderStatsCard(stats) {
  const width = 420;
  const height = 220;
  const rows = [
    ["Public + private repos", String(stats.repoCount)],
    ["Total stars", String(stats.stars)],
    ["Total forks", String(stats.forks)],
    ["Total issues (authored)", String(stats.issues)],
    ["Total PRs (authored)", String(stats.prs)],
    ["Languages repos used", String(stats.langCount)],
  ];
  const parts = [];
  parts.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`,
  );
  parts.push(
    `<style>
      .card{fill:#010409;stroke:#30363d}
      .title{fill:#e6edf3;font:600 14px -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif}
      .label{fill:#8b949e;font:400 12px -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif}
      .val{fill:#52adc8;font:700 14px ui-monospace,SFMono-Regular,Menlo,monospace}
      .sub{fill:#8b949e;font:400 11px -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif}
    </style>`,
  );
  parts.push(`<rect class="card" x="1" y="1" width="${width - 2}" height="${height - 2}" rx="8"/>`);
  parts.push(`<text class="title" x="18" y="26">GitHub Stats (token-visible)</text>`);
  let y = 56;
  for (const [label, val] of rows) {
    parts.push(`<text class="label" x="18" y="${y}">${escapeXml(label)}</text>`);
    parts.push(`<text class="val" x="${width - 18}" y="${y}" text-anchor="end">${escapeXml(val)}</text>`);
    y += 24;
  }
  parts.push(
    `<text class="sub" x="18" y="${height - 14}">Counts include repos this token can access</text>`,
  );
  parts.push(`</svg>`);
  return parts.join("\n");
}

async function main() {
  const repos = [];
  let page = 1;
  while (page <= 5) {
    const batch = await gh(
      `${API}/user/repos?per_page=100&page=${page}&affiliation=owner,collaborator,organization_member&sort=updated`,
    );
    if (!batch.length) break;
    repos.push(...batch);
    page += 1;
  }

  const langMap = new Map();
  let stars = 0;
  let forks = 0;
  let issues = 0;
  let prs = 0;

  for (const repo of repos) {
    stars += repo.stargazers_count || 0;
    forks += repo.forks_count || 0;

    try {
      const langs = await gh(`${API}/repos/${repo.full_name}/languages`);
      for (const [lang, bytes] of Object.entries(langs)) {
        if (!lang) continue;
        langMap.set(lang, (langMap.get(lang) || 0) + Number(bytes || 0));
      }
    } catch (e) {
      console.warn("langs fail", repo.full_name, e.message);
    }
  }

  // authored issues/PRs via search (includes private when token can see them)
  try {
    const me = await gh(`${API}/user`);
    const login = me.login;
    const iss = await gh(
      `${API}/search/issues?q=${encodeURIComponent(`author:${login} type:issue`)}&per_page=1`,
    );
    issues = iss.total_count || 0;
    const prq = await gh(
      `${API}/search/issues?q=${encodeURIComponent(`author:${login} type:pr`)}&per_page=1`,
    );
    prs = prq.total_count || 0;
  } catch (e) {
    console.warn("search counts fail", e.message);
  }

  const langs = [...langMap.entries()].filter(([, b]) => b > 0).sort((a, b) => b[1] - a[1]);
  const total = langs.reduce((s, [, b]) => s + b, 0);

  const outDir = path.join(process.cwd(), "assets");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "top-langs.svg"), renderTopLangs(langs, total), "utf8");
  fs.writeFileSync(
    path.join(outDir, "stats-token.svg"),
    renderStatsCard({
      repoCount: repos.length,
      stars,
      forks,
      issues,
      prs,
      langCount: langs.length,
    }),
    "utf8",
  );

  console.log("repos scanned:", repos.length);
  console.log("languages:", langs);
  console.log("total bytes:", total);
  console.log("stars/forks/issues/prs:", stars, forks, issues, prs);
  console.log("wrote assets/top-langs.svg and assets/stats-token.svg");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
